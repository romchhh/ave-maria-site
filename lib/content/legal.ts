export function getLegalPage(
  lang: Locale,
  slug: string
): LegalPage | undefined {
  return legalPages[lang].find((p) => p.slug === slug);
}

export function getLegalSlugs(): string[] {
  return legalPages.uk.map((p) => p.slug);
}
